import {
  existsSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, relative, resolve, sep } from "node:path";
import ts from "typescript";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const templatesRoot = resolve(projectRoot, "src", "templates");
const outputPath = resolve(templatesRoot, "generated.ts");
const templateIdPattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

const hasModifier = (node, kind) =>
  node.modifiers?.some((modifier) => modifier.kind === kind) ?? false;

const findComponentExport = (templatePath) => {
  const source = readFileSync(templatePath, "utf8");
  const sourceFile = ts.createSourceFile(
    templatePath,
    source,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TSX,
  );
  const exportedComponents = [];

  for (const statement of sourceFile.statements) {
    if (
      ts.isVariableStatement(statement) &&
      hasModifier(statement, ts.SyntaxKind.ExportKeyword)
    ) {
      for (const declaration of statement.declarationList.declarations) {
        const initializer = declaration.initializer;
        if (
          ts.isIdentifier(declaration.name) &&
          initializer &&
          (ts.isArrowFunction(initializer) || ts.isFunctionExpression(initializer))
        ) {
          exportedComponents.push(declaration.name.text);
        }
      }

      continue;
    }

    if (
      ts.isFunctionDeclaration(statement) &&
      hasModifier(statement, ts.SyntaxKind.ExportKeyword) &&
      statement.name
    ) {
      exportedComponents.push(statement.name.text);
    }
  }

  if (exportedComponents.includes("Template")) {
    return "Template";
  }

  if (exportedComponents.length === 1) {
    return exportedComponents[0];
  }

  throw new Error(
    `${relative(projectRoot, templatePath)} must export one React component. ` +
      'Prefer the named export `Template`.',
  );
};

const readTemplate = (entry) => {
  const id = entry.name;
  const folder = resolve(templatesRoot, id);
  const dataPath = resolve(folder, "data.json");
  const templatePath = resolve(folder, "template.tsx");
  const hasData = existsSync(dataPath);
  const hasTemplate = existsSync(templatePath);

  if (!hasData && !hasTemplate) {
    return null;
  }

  if (!templateIdPattern.test(id)) {
    throw new Error(
      `Invalid template folder "${id}". Use lowercase letters, numbers, and hyphens.`,
    );
  }

  if (!hasData || !hasTemplate) {
    const missing = [
      !hasData && "data.json",
      !hasTemplate && "template.tsx",
    ]
      .filter(Boolean)
      .join(" and ");
    throw new Error(`Template "${id}" is missing ${missing}.`);
  }

  let data;
  try {
    data = JSON.parse(readFileSync(dataPath, "utf8"));
  } catch (error) {
    throw new Error(
      `Could not parse ${relative(projectRoot, dataPath)}: ${error.message}`,
    );
  }

  if (!data || typeof data !== "object" || Array.isArray(data)) {
    throw new Error(`${relative(projectRoot, dataPath)} must contain a JSON object.`);
  }

  const exportName = findComponentExport(templatePath);
  return { id, exportName };
};

const entries = readdirSync(templatesRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .sort((a, b) => a.name.localeCompare(b.name))
  .map(readTemplate)
  .filter(Boolean);

if (entries.length === 0) {
  throw new Error(`No templates found in ${relative(projectRoot, templatesRoot)}.`);
}

const dataImports = entries.map(
  ({ id }, index) => `import json${index} from "./${id}/data.json";`,
);

const definitions = entries
  .map(
    ({ id }, index) => `
const sourceData${index} = json${index} as unknown as Record<string, unknown>;
const data${index} = normalizeTemplateData("${id}", sourceData${index});
const component${index}: ComponentType<{ data: TemplateData }> = ({ data }) =>
  createElement(componentExport${index}, {
    data: data as unknown as ComponentProps<typeof componentExport${index}>["data"],
  });
`,
  )
  .join("\n");

const componentImports = entries
  .map(
    ({ exportName }, index) =>
      `import { ${exportName} as componentExport${index} } from "./${entries[index].id}/template";`,
  )
  .join("\n");

const templateEntries = entries
  .map(
    ({ id }, index) => `  {
    id: "${id}",
    name:
      typeof sourceData${index}.templateName === "string"
        ? sourceData${index}.templateName
        : data${index}.title,
    description:
      typeof sourceData${index}.templateDescription === "string"
        ? sourceData${index}.templateDescription
        : data${index}.subtitle,
    component: component${index},
    data: data${index},
  }`,
  )
  .join(",\n");

const generated = `/* Generated by scripts/generate-template-registry.mjs. Do not edit. */
import { createElement } from "react";
import type { ComponentProps, ComponentType } from "react";
import type { TemplateData, TemplateDefinition } from "../types";
${dataImports.join("\n")}
${componentImports}

const normalizeTemplateData = (
  id: string,
  value: Record<string, unknown>,
): TemplateData => {
  const durationInSeconds = value.durationInSeconds ?? 10;
  if (
    typeof durationInSeconds !== "number" ||
    !Number.isFinite(durationInSeconds) ||
    durationInSeconds <= 0
  ) {
    throw new Error(
      \`Template "\${id}" must have a positive numeric durationInSeconds.\`,
    );
  }

  const optionalDimension = (key: "width" | "height" | "fps") => {
    const dimension = value[key];
    if (dimension === undefined) return undefined;
    if (typeof dimension !== "number" || !Number.isFinite(dimension) || dimension <= 0) {
      throw new Error(\`Template "\${id}" has an invalid \${key} value.\`);
    }
    return dimension;
  };

  return {
    ...value,
    title: typeof value.title === "string" ? value.title : id,
    subtitle: typeof value.subtitle === "string" ? value.subtitle : "",
    background:
      typeof value.background === "string" ? value.background : "#101426",
    accent: typeof value.accent === "string" ? value.accent : "#8b7bff",
    durationInSeconds,
    width: optionalDimension("width"),
    height: optionalDimension("height"),
    fps: optionalDimension("fps"),
  } as unknown as TemplateData;
};

${definitions}
export const templates: TemplateDefinition[] = [
${templateEntries}
];
`;

const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
if (current !== generated) {
  writeFileSync(outputPath, generated, "utf8");
}

for (const entry of entries) {
  const data = JSON.parse(
    readFileSync(resolve(templatesRoot, entry.id, "data.json"), "utf8"),
  );
  if (data.durationInSeconds === undefined) {
    console.warn(
      `Template "${entry.id}" has no durationInSeconds; using the documented 10-second default.`,
    );
  }
}

console.log(`Template registry ready (${entries.length} templates).`);
